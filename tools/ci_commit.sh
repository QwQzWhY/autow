#!/usr/bin/env bash
# Commit what the workflow just produced, and survive a push that races with it.
#
# The first version of this step ended in a bare `git push`. A code push and a
# bot commit landed within seconds of each other on 2026-10-13 and the scan run
# failed outright — it had committed its data on top of a revision that no longer
# existed on the remote.
set -euo pipefail

git config user.name "autow-bot"
git config user.email "autow-bot@users.noreply.github.com"
git add -A

if git diff --staged --quiet; then
  echo "没有变化，无需提交"
  exit 0
fi

git commit -q -m "chore: 更新待办 $(date -u '+%Y-%m-%d %H:%M UTC')"

for attempt in 1 2 3 4 5; do
  if git push -q; then
    echo "推送成功（第 ${attempt} 次）"
    exit 0
  fi
  echo "推送被拒，同步远端后重试（第 ${attempt} 次）"
  sleep 5
  git fetch -q origin main
  # Both sides can have touched the data files; the ones generated by this run
  # are the newer snapshot, so they win. `-X theirs` during a rebase means
  # "prefer the commit being replayed", which is ours.
  if ! git rebase -X theirs origin/main; then
    git rebase --abort || true
    echo "rebase 冲突，放弃本次提交" >&2
    exit 1
  fi
done

echo "连续 5 次推送失败" >&2
exit 1
